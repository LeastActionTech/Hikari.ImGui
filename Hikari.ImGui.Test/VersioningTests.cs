using System.Reflection;
using System.Text.RegularExpressions;
using Hikari.ImGui.Demo;
using NUnit.Framework;

namespace Hikari.ImGui.Test;

/// <summary>
/// Provides automated verification tests for the MinVer git-tag-based semantic versioning
/// and short commit hash build metadata conventions applied to <see cref="ImGui"/> and <see cref="ImGuiDemo"/>.
/// </summary>
[TestFixture]
public class VersioningTests
{
    /// <summary>
    /// Regular expression pattern matching a valid SemVer 2.0 version with a short commit hash build metadata suffix
    /// formatted according to the <c>&lt;version&gt;+&lt;short_hash&gt;</c> convention.
    /// </summary>
    private static readonly Regex s_semVerWithCommitHashRegex = new(
        @"^1\.93\.\d+(-[0-9A-Za-z.-]+)?\+[0-9a-fA-F]{7,}$",
        RegexOptions.Compiled);

    /// <summary>
    /// Verifies that the <c>Hikari.ImGui</c> core library assembly contains an informational version attribute
    /// matching the SemVer 2.0 git tag plus short commit hash convention.
    /// </summary>
    [Test]
    public void HikariImGui_InformationalVersion_FollowsGitTagAndShortCommitHashConvention()
    {
        Assembly assembly = typeof(ImGui).Assembly;
        AssemblyInformationalVersionAttribute? attr = assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>();

        Assert.That(attr, Is.Not.Null, "AssemblyInformationalVersionAttribute must be present on Hikari.ImGui.");
        Assert.That(attr!.InformationalVersion, Is.Not.Null.And.Not.Empty);

        Assert.That(
            attr.InformationalVersion,
            Does.Match(s_semVerWithCommitHashRegex.ToString()),
            $"Expected Hikari.ImGui InformationalVersion to follow SemVer + short commit hash convention, but got: {attr.InformationalVersion}");
    }

    /// <summary>
    /// Verifies that the <c>Hikari.ImGui.Demo</c> host application assembly contains an informational version attribute
    /// matching the SemVer 2.0 git tag plus short commit hash convention.
    /// </summary>
    [Test]
    public void HikariImGuiDemo_InformationalVersion_FollowsGitTagAndShortCommitHashConvention()
    {
        Assembly assembly = typeof(ImGuiDemo).Assembly;
        AssemblyInformationalVersionAttribute? attr = assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>();

        Assert.That(attr, Is.Not.Null, "AssemblyInformationalVersionAttribute must be present on Hikari.ImGui.Demo.");
        Assert.That(attr!.InformationalVersion, Is.Not.Null.And.Not.Empty);

        Assert.That(
            attr.InformationalVersion,
            Does.Match(s_semVerWithCommitHashRegex.ToString()),
            $"Expected Hikari.ImGui.Demo InformationalVersion to follow SemVer + short commit hash convention, but got: {attr.InformationalVersion}");
    }

    /// <summary>
    /// Verifies that both <c>Hikari.ImGui</c> and <c>Hikari.ImGui.Demo</c> assemblies share the exact same
    /// commit hash build metadata when built together in the solution.
    /// </summary>
    [Test]
    public void BothAssemblies_ShareIdenticalCommitHashBuildMetadata()
    {
        string? coreInfo = typeof(ImGui).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion;
        string? demoInfo = typeof(ImGuiDemo).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion;

        Assert.That(coreInfo, Is.Not.Null.And.Not.Empty);
        Assert.That(demoInfo, Is.Not.Null.And.Not.Empty);

        string coreHash = ExtractBuildMetadata(coreInfo!);
        string demoHash = ExtractBuildMetadata(demoInfo!);

        Assert.That(coreHash, Is.Not.Empty);
        Assert.That(demoHash, Is.Not.Empty);
        Assert.That(coreHash, Is.EqualTo(demoHash), "Hikari.ImGui and Hikari.ImGui.Demo must share the exact same commit hash.");
    }

    /// <summary>
    /// Verifies that the file versions generated by MinVer retain the expected major and minor versions (1.93).
    /// </summary>
    [Test]
    public void FileVersion_RetainsExpectedMajorAndMinor()
    {
        Assembly coreAssembly = typeof(ImGui).Assembly;
        AssemblyFileVersionAttribute? coreFileVer = coreAssembly.GetCustomAttribute<AssemblyFileVersionAttribute>();

        Assert.That(coreFileVer, Is.Not.Null);
        Assert.That(coreFileVer!.Version.StartsWith("1.93."), Is.True, $"FileVersion was {coreFileVer.Version}");
    }

    /// <summary>
    /// Extracts the build metadata portion (the string after the first <c>+</c> delimiter) from a version string.
    /// </summary>
    /// <param name="version">The full version string containing optional build metadata.</param>
    /// <returns>The build metadata portion if present; otherwise, an empty string.</returns>
    private static string ExtractBuildMetadata(string version)
    {
        int plusIndex = version.IndexOf('+');
        return plusIndex >= 0 && plusIndex < version.Length - 1 ? version[(plusIndex + 1)..] : string.Empty;
    }
}
